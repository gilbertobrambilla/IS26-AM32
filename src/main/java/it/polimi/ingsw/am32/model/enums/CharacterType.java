package it.polimi.ingsw.am32.model.enums;

/**
 * Lists the different types of character cards in the game.
 */
public enum CharacterType {
    /**
     * Represents an artist character.
     */
    ARTIST,
    /**
     * Represents a builder character.
     */
    BUILDER,
    /**
     * Represents a gatherer character.
     */
    GATHERER,
    /**
     * Represents a hunter character.
     */
    HUNTER,
    /**
     * Represents an inventor character.
     */
    INVENTOR,
    /**
     * Represents a shaman character.
     */
    SHAMAN
}
